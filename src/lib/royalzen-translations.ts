const TABLES: Record<string, Record<string, string>> = {
  en: ROYALZEN_EN,
  nl: ROYALZEN_NL,
  fr: ROYALZEN_FR
};

export function translateRoyalZenText(value: string, locale: string = "en") {
  if (locale === "zh") return value;
  const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return value;
  const [, leading, content, trailing] = match;
  /*
   * 顺序是有讲究的：本表的目标语言 → 语音端的表 → 英文兜底。
   *
   * 语音端的词条排在英文兜底之前，是因为那份表**已经填好了荷兰语和法语**，
   * 而这里的 NL/FR 还空着（等 Kimi 交）。排在后面的话，店员切到荷兰语，
   * 语音那一面会拿到英文回落，白白盖掉手上就有的荷兰语。
   * 等 Kimi 的内容进来，第一行自然就先命中了，这里不用再动。
   */
  const exact =
    TABLES[locale]?.[content] ?? translateVoiceText(content, locale) ?? ROYALZEN_EN[content];
  if (exact) return `${leading}${exact}${trailing}`;
  // 规则按 locale 分发，缺规则表时退回英文那份，不产出中文
  const rules = DYNAMIC_TRANSLATIONS[locale] ?? DYNAMIC_TRANSLATIONS.en ?? [];
  for (const [pattern, replace] of rules) {
    const dynamicMatch = content.match(pattern);
    if (dynamicMatch) return `${leading}${replace(...dynamicMatch)}${trailing}`;
  }
  return value;
}
